using System.Globalization;
using System.Text;
using System.Text.Json;

namespace LuaTools.Core;

/// <summary>
/// Reads and writes the LuaTools build files (luabuilds_*.lua) — small Lua tables
/// mapping appid to a depot manifest set. Same on-disk shape on every platform.
/// </summary>
public sealed class BuildStore
{
    private static readonly JsonSerializerOptions Options = new() { WriteIndented = true };

    public string Directory { get; }

    public BuildStore(string? directory = null)
    {
        Directory = directory ?? Path.Combine(PlatformPaths.AppDataDir, "builds");
        System.IO.Directory.CreateDirectory(Directory);
    }

    public sealed record BuildEntry(long AppId, string Name, IReadOnlyDictionary<long, long> DepotManifests);

    public IReadOnlyList<BuildEntry> List()
    {
        var results = new List<BuildEntry>();
        foreach (var file in System.IO.Directory.EnumerateFiles(Directory, "luabuilds_*.json"))
        {
            try
            {
                var entry = JsonSerializer.Deserialize<BuildEntry>(File.ReadAllText(file), Options);
                if (entry is not null) results.Add(entry);
            }
            catch (Exception ex)
            {
                Log.Warn($"build file {Path.GetFileName(file)} unreadable: {ex.Message}");
            }
        }
        return results.OrderBy(r => r.Name, StringComparer.OrdinalIgnoreCase).ToArray();
    }

    public BuildEntry? Get(long appId) => List().FirstOrDefault(b => b.AppId == appId);

    public string Save(BuildEntry entry)
    {
        var path = Path.Combine(Directory, $"luabuilds_{entry.AppId}.json");
        File.WriteAllText(path, JsonSerializer.Serialize(entry, Options));
        return path;
    }

    public void Delete(long appId)
    {
        var path = Path.Combine(Directory, $"luabuilds_{appId}.json");
        if (File.Exists(path)) File.Delete(path);
    }

    /// <summary>Writes the Lua table LuaTools injects, for parity with the Windows build.</summary>
    public static string ToLua(BuildEntry entry)
    {
        var sb = new StringBuilder();
        sb.AppendLine("-- generated by LuaTools");
        sb.AppendLine("addappid(" + entry.AppId.ToString(CultureInfo.InvariantCulture) + ")");
        foreach (var (depot, manifest) in entry.DepotManifests.OrderBy(k => k.Key))
        {
            sb.Append("addappid(")
              .Append(depot.ToString(CultureInfo.InvariantCulture))
              .Append(", 1, \"")
              .Append(manifest.ToString(CultureInfo.InvariantCulture))
              .AppendLine("\")");
        }
        return sb.ToString();
    }

    public string WriteLua(BuildEntry entry)
    {
        var path = Path.Combine(Directory, $"luabuilds_{entry.AppId}.lua");
        File.WriteAllText(path, ToLua(entry));
        return path;
    }
}
